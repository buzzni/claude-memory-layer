import { describe, expect, it } from 'vitest';

import { isHarnessBoilerplate } from '../../src/core/harness-boilerplate.js';
import { isCommandArtifactQuery, isLowSignalContextContent } from '../../src/core/retrieval-quality.js';
import { buildSessionQrelsFixtureFromJsonl } from '../../src/core/session-qrels.js';
import { isWorthStoringPrompt } from '../../src/services/session-history-importer.js';

const HARNESS_BLOCKS: Record<string, string> = {
  'slash command': '<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args></command-args>',
  'slash command message first': '<command-message>review is running…</command-message>\n<command-name>/review</command-name>',
  'slash command arguments': '<command-args>--effort high</command-args>',
  'local command output': '<local-command-stdout>Set model to opus (claude-opus-5-5)</local-command-stdout>',
  'local command stderr': '<local-command-stderr>Error: unknown command</local-command-stderr>',
  'local command caveat': '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>\n<command-name>/model</command-name>',
  'system reminder': '<system-reminder>\nThe TodoWrite tool hasn\'t been used recently. Consider using it to track progress.\n</system-reminder>',
  'task notification': '<task-notification>\n<task-id>b3k9</task-id>\n<status>completed</status>\n<summary>Background command finished</summary>\n</task-notification>',
  'system notification banner': '[SYSTEM NOTIFICATION - NOT USER INPUT]\nThis is an automated background-task event, NOT a message from the user.',
  'interrupted request': '[Request interrupted by user for tool use]',
  'image attachment record': '[Image: source: /Users/me/Desktop/screenshot-2026-10-31.png]',
  'skill preamble': 'Base directory for this skill: /Users/me/.claude/skills/review\n\n# Review\n\nReview the current diff for correctness bugs.'
};

const QUOTED_MARKER_QUERIES = [
  'retrieval-quality에서 command-name 단어만 언급해도 쿼리가 걸러지는 문제를 고쳐줘',
  'Why does the importer drop prompts that quote <command-name>/model</command-name> in the middle?',
  'The hook sees a <system-reminder> block appended after the user text; keep the user text searchable.',
  'Explain how [Request interrupted by user] markers end a turn in the Claude transcript.',
  'A pasted transcript had <command-name>/model</command-name> then <local-command-stdout>opus</local-command-stdout>; why was it dropped?',
  '[Image #1] 이 화면에서 버튼 정렬이 깨지는 원인을 찾아줘'
];

describe('harness boilerplate markers', () => {
  it.each(Object.entries(HARNESS_BLOCKS))('treats a message opening with a %s block as harness boilerplate', (_label, block) => {
    expect(isHarnessBoilerplate(block)).toBe(true);
    expect(isHarnessBoilerplate(`\n  ${block}`)).toBe(true);
  });

  it.each(QUOTED_MARKER_QUERIES)('treats a marker quoted after the opening as user text: %s', (query) => {
    expect(isHarnessBoilerplate(query)).toBe(false);
  });

  it('does not treat empty text as harness boilerplate', () => {
    expect(isHarnessBoilerplate('')).toBe(false);
    expect(isHarnessBoilerplate('   \n')).toBe(false);
  });
});

describe('callers share the harness boilerplate rule', () => {
  it.each(Object.entries(HARNESS_BLOCKS))('importer drops a %s block', (_label, block) => {
    expect(isWorthStoringPrompt(block)).toBe(false);
  });

  it.each(Object.entries(HARNESS_BLOCKS))('retrieval guard rejects a %s block as query and as context', (_label, block) => {
    expect(isCommandArtifactQuery(block)).toBe(true);
    expect(isLowSignalContextContent(block)).toBe(true);
  });

  it.each(QUOTED_MARKER_QUERIES)('importer keeps a prompt quoting a marker mid-body: %s', (query) => {
    expect(isWorthStoringPrompt(query)).toBe(true);
  });

  it.each(QUOTED_MARKER_QUERIES)('retrieval guard keeps a query quoting a marker mid-body: %s', (query) => {
    expect(isCommandArtifactQuery(query)).toBe(false);
    expect(isLowSignalContextContent(query)).toBe(false);
  });

  it('qrels extraction skips harness blocks and keeps prompts quoting a marker mid-body', () => {
    const turns = [
      HARNESS_BLOCKS['system reminder'],
      HARNESS_BLOCKS['skill preamble'],
      QUOTED_MARKER_QUERIES[0]
    ];
    const jsonl = turns.flatMap((text, index) => [
      JSON.stringify({ type: 'user', sessionId: 's1', message: { role: 'user', content: text } }),
      JSON.stringify({ type: 'assistant', sessionId: 's1', message: { role: 'assistant', content: `answer ${index} about retrieval quality guards` } })
    ]).join('\n');

    const fixture = buildSessionQrelsFixtureFromJsonl(jsonl, { name: 'harness-boilerplate', ks: [1] });

    expect(fixture.queries.map((query) => query.query)).toEqual([QUOTED_MARKER_QUERIES[0]]);
  });
});
